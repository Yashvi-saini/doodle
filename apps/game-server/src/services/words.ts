/** Picks `count` distinct random words. */
export function pickWords(
  count: number,
  words: readonly string[] = DEFAULT_WORDS,
  random: (max: number) => number = randomInt,
): string[] {
  const pool = [...words];
  const picked: string[] = [];
  while (picked.length < count && pool.length > 0) {
    const [word] = pool.splice(random(pool.length), 1);
    if (word) picked.push(word);
  }
  return picked;
}
